"""Repo-managed launchd deployment for the 48-hour live shadow (Stage 4 C).

Generates the wrapper script, LaunchAgent plist, and runner config from
repository truth for the user agent ``com.woongs.tokmo-v3-48h-shadow``:

- runtime artifacts under ``~/.hermes/runtime/tokmo-v3/48h-shadow`` (the
  project itself stays under ``~/tokmo``, keeping TCC prompts away from
  the agent), plist under ``~/Library/LaunchAgents``;
- ``RunAtLoad`` so the agent starts when loaded before 06:30 KST while the
  runner itself waits until ``2026-08-02T06:30:00+09:00``;
- ``KeepAlive={SuccessfulExit: False}`` so only a crash/nonzero exit
  relaunches; a successful COMPLETE campaign is inert, and the runner's
  durable state also refuses any relogin/reboot rerun;
- absolute, wrapper-rotated bounded stdout/stderr logs;
- a minimal environment: the wrapper sources ``~/.zshrc`` silently only
  for credentials and execs the exact project ``.venv/bin/python``.

``--dry-run`` prints the artifacts without writing; ``--install`` writes
them idempotently and never overwrites a plist it does not own;
``--doctor`` verifies the deployment; ``--uninstall`` removes only the
exact owned label/paths. This tool never calls ``launchctl load`` — actual
loading is a separate operator step.
"""

import argparse
import json
import os
import plistlib
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

_TOOL_DIR = Path(__file__).resolve().parent
_DEFAULT_PROJECT_ROOT = _TOOL_DIR.parent
if str(_DEFAULT_PROJECT_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(_DEFAULT_PROJECT_ROOT / "src"))

from tokmo.records.prelaunch_markers import (
    MarkerError,
    verify_pass_marker,
)

AGENT_LABEL = "com.woongs.tokmo-v3-48h-shadow"
START_AT_LOCAL = "2026-08-02T06:30:00+09:00"
CAMPAIGN_DURATION_SECONDS = 172800
CAMPAIGN_INTERVAL_SECONDS = 300
LOG_MAX_BYTES = 5 * 1024 * 1024


@dataclass(frozen=True)
class AgentPaths:
    home: Path
    project_root: Path
    runtime_root: Path
    wrapper: Path
    config: Path
    shadow_root: Path
    stdout_log: Path
    stderr_log: Path
    plist: Path
    venv_python: Path
    full_suite_marker: Path
    review_marker: Path


def resolve_paths(
    home: Path | None = None, project_root: Path | None = None
) -> AgentPaths:
    home = Path(home) if home is not None else Path.home()
    project_root = (
        Path(project_root) if project_root is not None else _DEFAULT_PROJECT_ROOT
    )
    runtime_root = home / ".hermes" / "runtime" / "tokmo-v3" / "48h-shadow"
    evidence = project_root / ".hermes" / "evidence" / "stage4"
    return AgentPaths(
        home=home,
        project_root=project_root,
        runtime_root=runtime_root,
        wrapper=runtime_root / "run_48h_shadow.zsh",
        config=runtime_root / "config.json",
        shadow_root=runtime_root / "shadow",
        stdout_log=runtime_root / "logs" / "stdout.log",
        stderr_log=runtime_root / "logs" / "stderr.log",
        plist=home / "Library" / "LaunchAgents" / f"{AGENT_LABEL}.plist",
        venv_python=project_root / ".venv" / "bin" / "python",
        full_suite_marker=evidence / "full_suite_pass.json",
        review_marker=evidence / "independent_review_pass.json",
    )


def generate_wrapper(paths: AgentPaths) -> str:
    return f"""#!/bin/zsh
# generated by tools/install_48h_shadow_agent.py — repository is the truth,
# do not hand-edit the installed copy
set -u
LOG_MAX_BYTES={LOG_MAX_BYTES}
for log in "{paths.stdout_log}" "{paths.stderr_log}"; do
  if [ -f "$log" ]; then
    size=$(/usr/bin/stat -f%z "$log" 2>/dev/null || echo 0)
    if [ "$size" -gt "$LOG_MAX_BYTES" ]; then
      /bin/mv "$log" "$log.1"
    fi
  fi
done
# credentials only; every diagnostic from the profile is discarded
source "$HOME/.zshrc" >/dev/null 2>&1
# Reuse the existing stock-monitor credential contract without copying or
# logging secret values.  The lifecycle adapter has deliberately explicit
# names so it cannot accidentally pick up the Hermes bot.
export TELEGRAM_STOCK_BOT_TOKEN="${{TELEGRAM_STOCK_BOT:-}}"
export TELEGRAM_STOCK_BOT_CHAT_ID="${{TELEGRAM_CHAT_ID:-}}"
export PYTHONPATH="{paths.project_root / "src"}"
exec "{paths.venv_python}" "{paths.project_root / "tools" / "run_48h_shadow.py"}" \\
  --config "{paths.config}"
"""


def generate_plist(paths: AgentPaths) -> str:
    return plistlib.dumps(
        {
            "Label": AGENT_LABEL,
            "ProgramArguments": [str(paths.wrapper)],
            "RunAtLoad": True,
            "KeepAlive": {"SuccessfulExit": False},
            "StandardOutPath": str(paths.stdout_log),
            "StandardErrorPath": str(paths.stderr_log),
            "WorkingDirectory": str(paths.project_root),
            "EnvironmentVariables": {
                "PATH": "/usr/bin:/bin",
                "HOME": str(paths.home),
            },
        }
    ).decode()


def generate_config(paths: AgentPaths, *, expected_commit: str) -> dict:
    return {
        "start_at": START_AT_LOCAL,
        "duration_seconds": CAMPAIGN_DURATION_SECONDS,
        "interval_seconds": CAMPAIGN_INTERVAL_SECONDS,
        "shadow_root": str(paths.shadow_root),
        "expected_commit": expected_commit,
        "full_suite_marker": str(paths.full_suite_marker),
        "review_marker": str(paths.review_marker),
        "mode": "live-shadow",
        "policy_version": "cadence-300s-v1",
        "lifecycle": "telegram",
    }


def _owned_plist_or_absent(paths: AgentPaths) -> None:
    if not paths.plist.exists():
        return
    try:
        current = plistlib.loads(paths.plist.read_bytes())
    except Exception as error:
        raise ValueError(f"refusing unreadable plist at {paths.plist}") from error
    if current.get("Label") != AGENT_LABEL:
        raise ValueError(
            f"refusing to touch unrelated plist {current.get('Label')!r} "
            f"at {paths.plist}"
        )


def install(paths: AgentPaths, *, expected_commit: str, dry_run: bool) -> list:
    """Write (or print) every artifact; idempotent and owned-paths-only."""
    artifacts = [
        ("wrapper", paths.wrapper, generate_wrapper(paths), 0o755),
        (
            "config",
            paths.config,
            json.dumps(
                generate_config(paths, expected_commit=expected_commit),
                indent=1,
                sort_keys=True,
            )
            + "\n",
            0o600,
        ),
        ("plist", paths.plist, generate_plist(paths), 0o644),
    ]
    if dry_run:
        return [
            {
                "action": "would-write",
                "artifact": name,
                "path": str(path),
                "content": content,
            }
            for name, path, content, _mode in artifacts
        ]
    _owned_plist_or_absent(paths)
    for directory in (paths.runtime_root, paths.stdout_log.parent, paths.shadow_root):
        directory.mkdir(mode=0o700, parents=True, exist_ok=True)
        os.chmod(directory, 0o700)
    paths.plist.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
    actions = []
    for name, path, content, mode in artifacts:
        path.write_text(content)
        os.chmod(path, mode)
        actions.append({"action": "wrote", "artifact": name, "path": str(path)})
    return actions


def uninstall(paths: AgentPaths) -> list:
    """Remove exactly the owned artifacts; shadow evidence is preserved."""
    _owned_plist_or_absent(paths)
    actions = []
    for name, path in (
        ("plist", paths.plist),
        ("wrapper", paths.wrapper),
        ("config", paths.config),
    ):
        if path.exists():
            path.unlink()
            actions.append({"action": "removed", "artifact": name, "path": str(path)})
    return actions


# -- doctor -----------------------------------------------------------------


def _git_head(project_root: Path) -> str | None:
    completed = subprocess.run(
        ["git", "-C", str(project_root), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=False,
    )
    return completed.stdout.strip() if completed.returncode == 0 else None


def _current_uid() -> int:
    return os.getuid()


def doctor(paths: AgentPaths, *, offline: bool = False) -> list:
    """Verify the deployment; every check reports ok/fail/skipped."""
    checks = []

    def report(check: str, ok: bool | None, detail: str) -> None:
        status = "skipped" if ok is None else ("ok" if ok else "fail")
        checks.append({"check": check, "status": status, "detail": detail})

    # plist: syntax, label, absolute paths, mode
    if paths.plist.is_file():
        lint = subprocess.run(
            ["plutil", "-lint", str(paths.plist)],
            capture_output=True,
            text=True,
            check=False,
        )
        report("plist_lint", lint.returncode == 0, lint.stdout.strip())
        try:
            plist = plistlib.loads(paths.plist.read_bytes())
        except Exception:
            plist = None
        report(
            "plist_label",
            plist is not None and plist.get("Label") == AGENT_LABEL,
            str(paths.plist),
        )
        report(
            "plist_paths_absolute",
            plist is not None
            and all(
                Path(value).is_absolute()
                for value in (
                    *plist.get("ProgramArguments", ["relative"]),
                    plist.get("StandardOutPath", "relative"),
                    plist.get("StandardErrorPath", "relative"),
                )
            ),
            "ProgramArguments/StandardOutPath/StandardErrorPath",
        )
        mode = paths.plist.stat().st_mode & 0o777
        report("plist_mode", mode == 0o644, oct(mode))
    else:
        for name in ("plist_lint", "plist_label", "plist_paths_absolute", "plist_mode"):
            report(name, False, f"absent {paths.plist}")

    report(
        "wrapper_executable",
        paths.wrapper.is_file() and os.access(paths.wrapper, os.X_OK),
        str(paths.wrapper),
    )
    report(
        "venv_python_executable",
        paths.venv_python.is_file() and os.access(paths.venv_python, os.X_OK),
        str(paths.venv_python),
    )

    # every owned artifact belongs to the invoking user
    owned_artifacts = [paths.plist, paths.wrapper, paths.config, paths.runtime_root]
    present_artifacts = [path for path in owned_artifacts if path.exists()]
    uid = _current_uid()
    foreign = [str(path) for path in present_artifacts if path.stat().st_uid != uid]
    report(
        "artifacts_owner",
        bool(present_artifacts) and not foreign,
        "; ".join(foreign) if foreign else f"uid={uid}",
    )

    # runtime root private and writable
    if paths.runtime_root.is_dir():
        mode = paths.runtime_root.stat().st_mode & 0o777
        report(
            "runtime_root_private_writable",
            mode == 0o700 and os.access(paths.runtime_root, os.W_OK),
            oct(mode),
        )
    else:
        report("runtime_root_private_writable", False, f"absent {paths.runtime_root}")

    # config: parse, commit, timestamps
    config = None
    if paths.config.is_file():
        try:
            config = json.loads(paths.config.read_text())
        except ValueError:
            config = None
    report("config_readable", config is not None, str(paths.config))
    expected_commit = (config or {}).get("expected_commit")
    head = _git_head(paths.project_root)
    report(
        "expected_commit_matches_head",
        config is not None and head is not None and expected_commit == head,
        f"head={head} expected={expected_commit}",
    )
    timestamps_ok = False
    if config is not None:
        try:
            start = datetime.fromisoformat(config["start_at"])
            timestamps_ok = (
                start.tzinfo is not None
                and int(start.timestamp()) % config["interval_seconds"] == 0
                and config["duration_seconds"] == CAMPAIGN_DURATION_SECONDS
            )
        except (KeyError, ValueError, TypeError):
            timestamps_ok = False
    report(
        "start_end_timestamps",
        timestamps_ok,
        f"start_at={None if config is None else config.get('start_at')} "
        f"duration={None if config is None else config.get('duration_seconds')}",
    )

    # PASS markers verify against the pinned commit (hashes, not booleans)
    for check, marker_path, kind in (
        ("marker_full_suite", paths.full_suite_marker, "full-suite"),
        ("marker_independent_review", paths.review_marker, "pilot-acceptance"),
    ):
        if config is None or expected_commit is None:
            report(check, False, "config unavailable")
            continue
        try:
            verify_pass_marker(
                marker_path,
                kind=kind,
                expected_commit=expected_commit,
            )
            report(check, True, str(marker_path))
        except MarkerError as error:
            report(check, False, str(error))

    # credential names only; values are never read into the report
    names = set()
    env_path = paths.project_root / ".env.toss"
    if env_path.is_file():
        for line in env_path.read_text().splitlines():
            if "=" in line and line.split("=", 1)[1].strip():
                names.add(line.split("=", 1)[0].strip())
    report(
        "credentials_names_present",
        {"TOSS_CLIENT_ID", "TOSS_CLIENT_SECRET"} <= names,
        "TOSS_CLIENT_ID,TOSS_CLIENT_SECRET",
    )

    # a currently running duplicate holds the runner flock
    lock_path = paths.shadow_root / "harness" / "runner.lock"
    if lock_path.exists():
        import fcntl

        descriptor = os.open(lock_path, os.O_RDWR)
        try:
            fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
            fcntl.flock(descriptor, fcntl.LOCK_UN)
            report("no_running_duplicate", True, "lock free")
        except BlockingIOError:
            report("no_running_duplicate", False, "runner already holds lock")
        finally:
            os.close(descriptor)
    else:
        report("no_running_duplicate", True, "no lock file")

    if offline:
        report("launchctl_status", None, "offline: launchctl not queried")
    else:
        status = subprocess.run(
            ["launchctl", "print", f"gui/{os.getuid()}/{AGENT_LABEL}"],
            capture_output=True,
            text=True,
            check=False,
        )
        report(
            "launchctl_status",
            status.returncode == 0,
            "loaded" if status.returncode == 0 else "not loaded",
        )
    return checks


# -- CLI --------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="install-48h-shadow-agent")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--install", action="store_true")
    parser.add_argument("--doctor", action="store_true")
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--home")
    parser.add_argument("--project-root")
    parser.add_argument("--expected-commit")
    try:
        args = parser.parse_args(argv)
    except SystemExit:
        return 1
    actions = [args.dry_run, args.install, args.doctor, args.uninstall]
    if sum(actions) != 1:
        print(
            "exactly one of --dry-run/--install/--doctor/--uninstall", file=sys.stderr
        )
        return 1
    paths = resolve_paths(
        home=args.home,
        project_root=args.project_root,
    )
    if args.dry_run or args.install:
        expected_commit = args.expected_commit or _git_head(paths.project_root)
        if expected_commit is None:
            print("expected commit unavailable", file=sys.stderr)
            return 1
        try:
            results = install(
                paths,
                expected_commit=expected_commit,
                dry_run=args.dry_run,
            )
        except ValueError as error:
            print(str(error), file=sys.stderr)
            return 1
        for entry in results:
            print(f"{entry['action']}: {entry['path']}")
            if args.dry_run:
                print(entry["content"])
        return 0
    if args.uninstall:
        try:
            for entry in uninstall(paths):
                print(f"{entry['action']}: {entry['path']}")
        except ValueError as error:
            print(str(error), file=sys.stderr)
            return 1
        return 0
    checks = doctor(paths, offline=args.offline)
    for entry in checks:
        print(f"{entry['status']:>7}  {entry['check']}  {entry['detail']}")
    return 0 if all(entry["status"] in ("ok", "skipped") for entry in checks) else 1


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
